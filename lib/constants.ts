// Get only visible buildings
export const BUILDINGS = Object.fromEntries(
  Object.entries(BUILDING_CONFIG)
    .filter(([, config]) => config.visible)
    .map(([key, config]) => [key, { rooms: config.rooms }])
);

// Shared by the /calendar builder UI and the /api/calendar.ics route so the
// advertised cap and the enforced cap can never diverge.
export const MAX_CLASSES = 20;

/**
 * Shared whole-entity normalization for scraped names (rooms, teachers):
 * collapse whitespace, trim, casefold. Matching must use this rule
 * everywhere so the same entity never compares unequal.
 */
export const normalizeEntity = (value: string): string =>
  value
    .replace(/[\u2010-\u2015\u2212]/g, "-")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();

// Upstream marks study-room events with "Aule studio" as the whole
// description (the type cell then says "Attivita'"); older feeds carry the
// marker in the type cell. Only exact whole-value matches count: substring
// rules on the free-text class title made real classes look like free time.
const STUDY_MARKERS = ["aule studio", "aula studio"];

const VIRTUAL_ROOM_MARKERS = ["virtual", "off campus", "fuori sede", "live room"];

/**
 * Upstream also lists non-rooms (virtual attendance markers) in the room
 * cell; those must never link to a room page.
 */
export function isLinkableRoomName(roomName: string): boolean {
  const normalized = normalizeEntity(roomName);
  return normalized.length > 0 && !VIRTUAL_ROOM_MARKERS.some((marker) => normalized.includes(marker));
}

const hasStudyMarker = (event: { type: string; description: string }) =>
  STUDY_MARKERS.includes(normalizeEntity(event.type)) ||
  STUDY_MARKERS.includes(normalizeEntity(event.description));

/** Event marking the room as free for general use. */
export function isFreeTimeEvent(event: { type: string; description: string }): boolean {
  return hasStudyMarker(event) || normalizeEntity(event.type) === "studio";
}

/** Event marking the room as an official study room. */
export function isStudyRoomEvent(event: { type: string; description: string }): boolean {
  return hasStudyMarker(event);
}

/**
 * Get building display name from config
 */
export function getBuildingDisplayName(buildingKey: string): string {
  return BUILDING_CONFIG[buildingKey]?.displayName || buildingKey;
}

/**
 * Get visible buildings with display names
 */
export function getVisibleBuildings(): Record<string, string> {
  return Object.fromEntries(
    Object.entries(BUILDING_CONFIG)
      .filter(([, config]) => config.visible)
      .map(([key, config]) => [key, config.displayName])
  );
}

/**
 * Get all valid room names from the buildings list
 */
export function getAllValidRooms(): Set<string> {
  const validRooms = new Set<string>();
  Object.values(BUILDINGS).forEach((building) => {
    building.rooms.forEach((room) => {
      validRooms.add(room);
    });
  });
  return validRooms;
}

/**
 * Canonical room lookup: the scraped placement puts free-text parts after the
 * building ("Aula 1, Sarfatti 25, Piano 1"), so the scraped building string
 * is untrustable; the room name is the reliable key. Rooms are enumerated in
 * BUILDINGS, so a room missing here is truly untracked.
 */
let canonicalRooms: Map<string, { building: string; room: string }> | null =
  null;
export function resolveRoom(
  roomName: string
): { building: string; room: string } | null {
  canonicalRooms ??= new Map(
    Object.entries(BUILDINGS).flatMap(([building, { rooms }]) =>
      rooms.map((room) => [normalizeEntity(room), { building, room }] as const)
    )
  );
  return canonicalRooms.get(normalizeEntity(roomName)) ?? null;
}

/**
 * Check if a room name is in the valid rooms list, using the shared
 * whole-entity normalization so " Aula 1 " matches "Aula 1".
 */
let normalizedValidRooms: Set<string> | null = null;
export function isValidRoom(roomName: string): boolean {
  normalizedValidRooms ??= new Set([...getAllValidRooms()].map(normalizeEntity));
  return normalizedValidRooms.has(normalizeEntity(roomName));
}
